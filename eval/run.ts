// Scores every labeled query in all three modes and writes eval/results.md.
// Usage: pnpm eval
import { writeFileSync } from 'node:fs';
import type { SearchMode } from 'shared';
import {
  contentHashes,
  embedder,
  gitCommit,
  loadQueries,
  MODES,
  openDatabase,
  RESULTS_PATH,
  runMode,
  type QueryGroup,
} from './lib.js';

/** Metrics are computed at 10, the number of results a user actually looks at. */
const K = 10;

interface ModeStats {
  recall: number[];
  mrr: number[];
  latencies: number[];
}

const emptyStats = (): ModeStats => ({ recall: [], mrr: [], latencies: [] });

function mean(values: number[]): number {
  return values.length === 0 ? 0 : values.reduce((sum, value) => sum + value, 0) / values.length;
}

function percentile(values: number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const index = Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length));
  return sorted[index]!;
}

function format(value: number, digits = 3): string {
  return value.toFixed(digits);
}

const { db, close } = openDatabase();
const deps = { db, embedder: embedder() };

try {
  const queries = loadQueries();
  const labeled = queries.filter((query) => query.relevant.length > 0);

  if (labeled.length === 0) {
    console.log(
      `eval: ${queries.length} queries, none labeled yet.\n` +
        'Relevance judgements are the owner\'s: run "pnpm --filter eval label" and answer y/n.\n' +
        'No results file was written, because there is nothing measured to write.',
    );
    process.exit(0);
  }

  const stats = new Map<SearchMode, ModeStats>(MODES.map((mode) => [mode, emptyStats()]));
  const byGroup = new Map<QueryGroup, Map<SearchMode, number[]>>();

  for (const query of labeled) {
    for (const mode of MODES) {
      const { results, ms } = await runMode(deps, mode, query.query);
      const top = results.slice(0, K);
      const hashes = await contentHashes(
        db,
        top.map((result) => result.job.id),
      );
      const retrieved = top.map((result) => hashes.get(result.job.id) ?? '');
      const relevant = new Set(query.relevant);

      const hits = retrieved.filter((hash) => relevant.has(hash)).length;
      const firstHit = retrieved.findIndex((hash) => relevant.has(hash));

      const modeStats = stats.get(mode)!;
      modeStats.recall.push(hits / relevant.size);
      modeStats.mrr.push(firstHit === -1 ? 0 : 1 / (firstHit + 1));
      modeStats.latencies.push(ms);

      const group = byGroup.get(query.group) ?? new Map<SearchMode, number[]>();
      group.set(mode, [...(group.get(mode) ?? []), hits / relevant.size]);
      byGroup.set(query.group, group);
    }
    console.log(`eval: ${query.id} done`);
  }

  const commit = gitCommit();
  const lines: string[] = [
    '# TalentLens — Evaluation results',
    '',
    `Generated by \`pnpm eval\` at commit \`${commit}\` on ${new Date().toISOString().slice(0, 10)}.`,
    '',
    `Queries: ${labeled.length} of ${queries.length} labeled. Metrics at k = ${K}.`,
    "Relevance judgements are the owner's, keyed by job content hash so they survive re-ingestion.",
    '',
    '| Mode | Recall@10 | MRR@10 | mean latency | p50 latency |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const mode of MODES) {
    const modeStats = stats.get(mode)!;
    lines.push(
      `| ${mode} | ${format(mean(modeStats.recall))} | ${format(mean(modeStats.mrr))} | ` +
        `${format(mean(modeStats.latencies), 1)} ms | ${format(percentile(modeStats.latencies, 50), 1)} ms |`,
    );
  }

  lines.push('', '## Recall@10 by query type', '', '| Query type | ' + MODES.join(' | ') + ' |');
  lines.push('| --- |' + MODES.map(() => ' --- |').join(''));
  for (const [group, modes] of byGroup) {
    lines.push(`| ${group} | ` + MODES.map((mode) => format(mean(modes.get(mode) ?? []))).join(' | ') + ' |');
  }
  lines.push('');

  writeFileSync(RESULTS_PATH, `${lines.join('\n')}\n`);
  console.log(`\n${lines.slice(7).join('\n')}`);
  console.log(`eval: wrote ${RESULTS_PATH}`);
} finally {
  await close();
}
